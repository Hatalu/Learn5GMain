/** แปลงข้อความเป็น Rich: ขึ้นต้น $ = สูตรทั้งข้อความ หรือมีส่วน $...$ อยู่ท้าย */
export function rich(s: string): Rich {
  if (!s.startsWith('$')) return [{ t: 'x', v: s }];
  const body = s.slice(1);
  const cut = body.indexOf('$');
  if (cut < 0) return [{ t: 'm', v: body }];
  return [{ t: 'm', v: body.slice(0, cut) }, { t: 'x', v: body.slice(cut + 1) }];
}

/** สร้างเนื้อหาชุดคำถามจากแม่แบบ: คำตอบถูกวนตำแหน่งไม่ให้อยู่ข้อ ก ตลอด */
export function buildSetTemplate(t: SetTemplate): QuizContent {
  return {
    v: 1,
    questions: t.qs.map(([q, right, ...wrong], i) => {
      const choices = wrong.map((w) => ({ ...newChoice(false), text: rich(w) }));
      choices.splice(i % 4, 0, { ...newChoice(true), text: rich(right) });
      return { id: uid(), text: rich(q), media: null, choices, multi: false, time: DEFAULT_TIME, points: 1 };
    }),
  };
}
